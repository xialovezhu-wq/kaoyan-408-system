"""Optional, public-only semantic shadow over a fixed 408 concept projection.

The existing native identity router remains first. This module never installs,
indexes on query, changes global settings, or falls back to a cloud service.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import unicodedata


PUBLIC_KINDS = {"concept", "knowledge_point", "knowledge_subpoint", "syllabus_entry"}
SUBJECTS = {"DS": "数据结构", "CO": "计算机组成原理", "OS": "操作系统", "CN": "计算机网络"}
IDENTITY_RE = re.compile(r"(?<![A-Za-z0-9])(?:EXAM408-\d{4}-Q\d+(?:-P\d+)?|(?:DS|CO|OS|CN)\d{2}-\d+|(?:DS|CO|OS|CN)_[A-Z0-9_]+|KSP-[A-Z0-9-]+|S27-[A-Z0-9-]+|KLR-[A-Z0-9-]+|EVU?408-[A-Z0-9-]+)(?![A-Za-z0-9])", re.I)
PRIVATE_RE = re.compile(r"我(?:上次|不懂|弄错|做错|总是)|用户(?:已经掌握|提示后|独立做对)|学习者(?:已经|仍然)|提示后(?:完成|理解)|独立做对|正确(?:答案|选项)|答案\s*(?:为|是|[:：])|/Users/|/Volumes/")


def _bytes(value):
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n").encode()


def _sha(value):
    return hashlib.sha256(_bytes(value)).hexdigest()


def native_identity_query(query):
    return bool(isinstance(query, str) and IDENTITY_RE.search(unicodedata.normalize("NFKC", query)))


def public_semantic_projection(documents):
    """Select only the root-authorized public fields, with no inherited scopes.

    Aliases are already source-reviewed by the concept compiler. Long phrases,
    IDs, duplicates and explicit personal/answer text are rejected here; no
    extra synonyms or textbook facts are generated by this adapter.
    """
    result, excluded, rejected_aliases = [], {}, 0
    for document in documents:
        if not document.get("searchable", True) or document.get("kind") not in PUBLIC_KINDS:
            excluded[document.get("kind", "unknown")] = excluded.get(document.get("kind", "unknown"), 0) + 1
            continue
        if (document.get("authority") != "public_objective_projection"
                or (document.get("scope") or {}).get("public_concept") is not True):
            raise ValueError("semantic_document_not_verified_public_projection")
        identity = document.get("id")
        if not isinstance(identity, str) or not re.fullmatch(r"[A-Za-z0-9_-]+", identity):
            raise ValueError("semantic_document_identity_invalid")
        title = str(document.get("title") or "").strip()
        if not title or len(title) > 180 or PRIVATE_RE.search(title):
            raise ValueError("semantic_public_title_invalid:" + identity)
        fields = document.get("fields") or {}
        values = {}
        for key in ("description", "exam_entry", "keywords"):
            value = fields.get(key, "")
            if isinstance(value, list):
                if not all(isinstance(part, str) for part in value):
                    raise ValueError("semantic_public_field_invalid:" + identity)
                value = "；".join(dict.fromkeys(part.strip() for part in value if part.strip()))
            if not isinstance(value, str) or len(value) > 6000 or PRIVATE_RE.search(value):
                raise ValueError("semantic_public_field_rejected:" + identity + ":" + key)
            values[key] = value.strip()
        aliases, seen = [], {unicodedata.normalize("NFKC", title).casefold()}
        for alias in document.get("aliases", []):
            if not isinstance(alias, str):
                rejected_aliases += 1
                continue
            alias = alias.strip()
            normalized = unicodedata.normalize("NFKC", alias).casefold()
            if (not alias or len(alias) > 80 or "\n" in alias or native_identity_query(alias)
                    or PRIVATE_RE.search(alias) or normalized in seen):
                rejected_aliases += 1
                continue
            seen.add(normalized)
            aliases.append(alias)
        code = str(document.get("knowledge_point") or identity)
        subject_match = re.search(r"(?:^|[-_])(DS|CO|OS|CN)(?=\d|[-_]|$)", code)
        subject = SUBJECTS.get(subject_match[1]) if subject_match else None
        lines = ["---", "title: " + json.dumps(title, ensure_ascii=False), "---", "", "# " + title]
        if subject:
            lines.extend(["", "学科：" + subject])
        for key, label in (("description", "概念说明"), ("exam_entry", "考查提示"), ("keywords", "机制词")):
            if values[key]:
                lines.extend(["", label + "：" + values[key]])
        if aliases:
            lines.extend(["", "同义称呼：" + "；".join(aliases)])
        text = "\n".join(lines) + "\n"
        result.append({"id": identity, "kind": document["kind"], "title": title, "text": text,
            "text_sha256": hashlib.sha256(text.encode()).hexdigest(),
            "source_refs": [ref for ref in document.get("source_refs", []) if isinstance(ref, dict)
                and not any(term in str(ref.get("field", "")) for term in ("scope", "association", "parent"))]})
    result.sort(key=lambda row: row["id"])
    if len({row["id"] for row in result}) != len(result):
        raise ValueError("semantic_public_identity_duplicate")
    identity_material = [{key: row[key] for key in ("id", "kind", "text_sha256")} for row in result]
    return {"schema": "cs408-public-semantic-projection-v1", "documents": result,
        "projection_sha256": _sha(identity_material), "document_count": len(result),
        "excluded_kind_counts": excluded, "rejected_alias_count": rejected_aliases,
        "text_fields": ["title", "subject_from_code", "description", "exam_entry", "keywords", "clean_aliases"],
        "private_fields_included": False, "formal_write_count": 0}


def _node_call(request, *, node="node", timeout=120):
    env = {key: value for key, value in os.environ.items()
           if not any(token in key.upper() for token in ("API_KEY", "TOKEN", "SECRET", "PASSWORD"))}
    completed = subprocess.run([node, str(Path(__file__).with_suffix(".mjs"))],
        input=json.dumps(request, ensure_ascii=False), text=True, capture_output=True,
        env=env, timeout=timeout, check=False)
    try:
        result = json.loads(completed.stdout)
    except (ValueError, TypeError) as exc:
        raise ValueError("semantic_adapter_invalid_output") from exc
    if not isinstance(result, dict):
        raise ValueError("semantic_adapter_invalid_output")
    return result


def rank_semantic(query, allowed_ids, limit=8, *, runtime_root, index_path, manifest_path,
                  model_path, kinds=None, expected_projection_hash=None, intent="concept", trial=False,
                  node="node", timeout=120):
    if native_identity_query(query):
        return {"status": "native_exact_required", "candidates": [], "model_call_count": 0, "index_write_count": 0}
    if intent != "concept" or trial is not True:
        return {"status": "unavailable", "reason": "semantic_public_shadow_only", "candidates": [], "model_call_count": 0}
    if not isinstance(query, str) or not query.strip() or len(query) > 1000:
        raise ValueError("semantic_query_invalid")
    manifest = json.loads(Path(manifest_path).read_text())
    if expected_projection_hash is not None and manifest.get("projection_sha256") != expected_projection_hash:
        return {"status": "unavailable", "reason": "semantic_public_projection_stale", "candidates": [], "model_call_count": 0}
    result = _node_call({"operation": "query", "intent": "concept", "trial": True,
        "runtimeRoot": str(Path(runtime_root).resolve()), "indexPath": str(Path(index_path).resolve()),
        "modelPath": str(Path(model_path).resolve()), "manifest": manifest, "query": query,
        "allowedIds": list(allowed_ids), "kinds": kinds, "limit": limit}, node=node, timeout=timeout)
    result["index_projection_hash"] = manifest.get("projection_sha256")
    return result


def rank_semantic_batch(queries, allowed_ids, limit=8, *, runtime_root, index_path, manifest_path,
                        model_path, kinds=None, expected_projection_hash=None, trial=False,
                        node="node", timeout=180):
    """Bounded trial batch shares one local model; never broadens per-query scope."""
    if trial is not True:
        return {"status": "unavailable", "reason": "semantic_public_shadow_only", "rows": [], "model_call_count": 0}
    if not isinstance(queries, list) or not 1 <= len(queries) <= 40 or any(
            not isinstance(row, dict) or not isinstance(row.get("query"), str) for row in queries):
        raise ValueError("semantic_query_batch_invalid")
    if all(native_identity_query(row["query"]) for row in queries):
        return {"status": "ready", "rows": [{"id": row.get("id"), "status": "native_exact_required",
            "candidates": [], "model_call_count": 0} for row in queries], "index_write_count": 0}
    manifest = json.loads(Path(manifest_path).read_text())
    if expected_projection_hash is not None and manifest.get("projection_sha256") != expected_projection_hash:
        return {"status": "unavailable", "reason": "semantic_public_projection_stale", "rows": [], "model_call_count": 0}
    return _node_call({"operation": "query_batch", "intent": "concept", "trial": True, "queries": queries,
        "runtimeRoot": str(Path(runtime_root).resolve()), "indexPath": str(Path(index_path).resolve()),
        "modelPath": str(Path(model_path).resolve()), "manifest": manifest,
        "allowedIds": list(allowed_ids), "kinds": kinds, "limit": limit}, node=node, timeout=timeout)


DEFAULT_RERANKER_SHA256 = "22c9979ce4fbcdc5acdc310c6641c32797eff1aa980b8f7a2db8a8ea23429a48"


def rerank_semantic_batch(queries, *, runtime_root, index_path, manifest_path, model_path,
                          expected_projection_hash, allowed_ids=None, kinds=None, limit=8,
                          model_sha256=DEFAULT_RERANKER_SHA256, trial=False, node="node", timeout=300):
    """Rerank at most twenty public SQL documents per already-scoped query.

    Candidate text is fetched from the same immutable-public index binding;
    caller snippets are never accepted. Batch mode shares one local model.
    """
    if trial is not True:
        return {"status": "unavailable", "reason": "reranker_shadow_only", "rows": [], "model_call_count": 0}
    if not isinstance(queries, list) or not 1 <= len(queries) <= 40:
        raise ValueError("rerank_batch_invalid")
    if type(limit) is not int or not 1 <= limit <= 20:
        raise ValueError("rerank_limit_invalid")
    rows = []
    for row in queries:
        query = row.get("query")
        if not isinstance(query, str) or not query.strip() or len(query) > 1000:
            raise ValueError("rerank_query_invalid")
        candidates = row.get("candidate_ids", row.get("candidates", []))
        if not isinstance(candidates, list) or len(candidates) > 20:
            raise ValueError("rerank_max_twenty_candidates")
        ids = [candidate.get("id") if isinstance(candidate, dict) else candidate for candidate in candidates]
        if any(not isinstance(identity, str) or not identity for identity in ids):
            raise ValueError("rerank_candidate_identity_invalid")
        if allowed_ids is not None and any(identity not in set(allowed_ids) for identity in ids):
            raise ValueError("rerank_candidate_outside_allowed_scope")
        rows.append({"id": row.get("id"), "query": query, "candidateIds": list(dict.fromkeys(ids))})
    if all(native_identity_query(row["query"]) for row in rows):
        return {"status": "ready", "rows": [{"id": row.get("id"), "status": "native_exact_required", "candidates": [], "model_call_count": 0} for row in rows], "index_write_count": 0}
    manifest = json.loads(Path(manifest_path).read_text())
    if not expected_projection_hash or manifest.get("projection_sha256") != expected_projection_hash:
        return {"status": "unavailable", "reason": "rerank_public_projection_stale", "rows": [], "model_call_count": 0}
    return _node_call({"operation": "rerank_scoped_batch", "intent": "concept", "trial": True,
        "runtimeRoot": str(Path(runtime_root).resolve()), "indexPath": str(Path(index_path).resolve()),
        "manifest": manifest, "expectedProjectionHash": expected_projection_hash,
        "rerankerPath": str(Path(model_path).resolve()), "rerankerSha256": model_sha256,
        "queries": rows, "allowedIds": list(allowed_ids) if allowed_ids is not None else None,
        "kinds": kinds, "limit": limit}, node=node, timeout=timeout)


def rerank_semantic(query, candidate_ids, **options):
    result = rerank_semantic_batch([{"id": "query", "query": query, "candidate_ids": candidate_ids}], **options)
    if result.get("status") != "ready" or not result.get("rows"):
        return result
    return {**{key: value for key, value in result.items() if key != "rows"}, **result["rows"][0]}
